import assert from 'node:assert/strict';
import {calculate} from '../../craft/frontend/calculator.js';
const ingredient=(id,quantity)=>({id,name:id,quantity});
const beer={inputs:[ingredient('wheat',5),ingredient('water',6),ingredient('yeast',2),ingredient('sugar',1)]};
assert.deepEqual(calculate(beer,100).leaves.map(row=>row.need),[100,200,600,500]);
assert.equal(calculate(beer,100,{}, {wheat:100}).rows.find(row=>row.id==='wheat').need,400);
assert.equal(calculate(beer,100,{}, {wheat:null}).rows.find(row=>row.id==='wheat').owned,null);
assert.throws(()=>calculate(beer,0));assert.throws(()=>calculate(beer,1.5));
const root={inputs:[ingredient('A',1),ingredient('B',1)]};
const expansions={A:{recipe:{inputs:[ingredient('C',3)]},yield:1},B:{recipe:{inputs:[ingredient('C',2)]},yield:1},C:{recipe:{inputs:[ingredient('raw',2)]},yield:3}};
const plan=calculate(root,1,expansions,{C:1});
assert.equal(plan.rows.find(row=>row.id==='C').total,5,'shared intermediates aggregate before rounding');
assert.equal(plan.rows.find(row=>row.id==='C').batches,2,'shared stock is subtracted once');
assert.equal(plan.leaves[0].need,4);
assert.throws(()=>calculate(root,1,{A:{recipe:{inputs:[ingredient('A',1)]},yield:1}}),/되돌아오는/);
assert.throws(()=>calculate(root,1,{A:{recipe:{inputs:[]},yield:0}}));
assert.throws(()=>calculate({inputs:[ingredient('A',Number.MAX_SAFE_INTEGER)]},2));
assert.equal(calculate({inputs:[ingredient('A',null)]},1).leaves[0].need,null);
const missing=calculate({inputs:[ingredient('A',null)]},1,{A:{recipe:{inputs:[ingredient('B',2)]},yield:1}});
assert.equal(missing.leaves[0].need,null,'unknown amounts propagate to descendants');
assert.equal(calculate(root,1,expansions,{A:1,B:1}).leaves[0].need,0);
console.log('PASS: craft counts, shared stock, aggregate rounding, unknowns, zero demand, cycles and numeric limits');
